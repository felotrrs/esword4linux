def _h(x: int, key_words: list, k: int) -> int:
    """Función h del Twofish (con las S-box keys) — definición myref."""
    xb = _u32_to_words(x)
    xb.reverse()
    l = [_u32_to_words(w) for w in key_words]
    y = xb[:]
    for i in range(k - 1, -1, -1):
        for j in range(4):
            y[j] = _qpermute(y[j], _QDONES[i + 1][j]) ^ l[i][j]
    for j in range(4):
        y[j] = _qpermute(y[j], _QDONES[0][j])
    z = _matrix_multiply(_MDS, y, _GF_MOD)
    return _words_to_u32(z)


def _key_schedule(key: bytes):
    """Genera las subkeys K[40], k y las S-box keys S a partir de la clave (16 bytes).

    Convención idéntica a `myref.py`: las palabras de la clave son big-endian
    (el vector I=3 del C++ usa bytes `9F 58 9F 5C...` = palabras `0x9F589F5C...`).
    """
    key_len = len(key)
    n = key_len * 8
    k = (n + 63) // 64
    key_words = list(struct.unpack(">IIII", key.ljust(16, b"\x00")[:16]))
    me = key_words[0:2 * k:2]
    mo = key_words[1:2 * k:2]

    s = []
    for i in range(k):
        x1 = _u32_to_words(me[i])
        x2 = _u32_to_words(mo[i])
        vector = x1 + x2
        prod = _matrix_multiply(_RS, vector, _RS_MOD)
        prod.reverse()
        s.insert(0, _words_to_u32(prod))

    subkeys = []
    rho = 0x01010101
    for i in range(_ROUNDS + 4):
        a = _h(2 * i * rho, me, k)
        b = _rol(_h((2 * i + 1) * rho, mo, k), 8)
        subkeys.append((a + b) & 0xFFFFFFFF)
        subkeys.append(_rol((a + 2 * b) & 0xFFFFFFFF, 9))
    return subkeys, k, s


def _g(x: int, s_box_keys: list, k: int) -> int:
    return _h(x, s_box_keys, k)


def _encrypt_block(subkeys, k, s_box_keys, block: bytes) -> bytes:
    """Cifra un bloque de 16 bytes en modo ECB."""
    pt = list(struct.unpack(">IIII", block))
    # BSWAP (igual que C++ en little-endian: leer como u32 LE → swap a BE para el algoritmo)
    pt = [struct.unpack(">I", struct.pack("<I", x))[0] for x in pt]
    r = [pt[i] ^ subkeys[i] for i in range(4)]
    for rnd in range(_ROUNDS):
        nr = [0, 0, 0, 0]
        f0, f1 = _f(r[0], r[1], rnd, subkeys, k, s_box_keys)
        nr[2] = _ror(r[2] ^ f0, 1)
        nr[3] = _rol(r[3], 1) ^ f1
        nr[0] = r[0]
        nr[1] = r[1]
        r = nr
        if rnd < _ROUNDS - 1:
            r[0], r[2] = r[2], r[0]
            r[1], r[3] = r[3], r[1]
    r = [r[2], r[3], r[0], r[1]]
    r = [r[(i + 2) % 4] ^ subkeys[i + 4] for i in range(4)]
    r = [struct.unpack(">I", struct.pack("<I", x))[0] for x in r]
    return struct.pack(">IIII", *r)


def _f(r0: int, r1: int, rnd: int, subkeys, k: int, s_box_keys) -> tuple:
    t0 = _g(r0, s_box_keys, k)
    t1 = _g(_rol(r1, 8), s_box_keys, k)
    f0 = (t0 + t1 + subkeys[2 * rnd + 8]) & 0xFFFFFFFF
    f1 = (t0 + 2 * t1 + subkeys[2 * rnd + 9]) & 0xFFFFFFFF
    return f0, f1


def _decrypt_block(subkeys, k, s_box_keys, block: bytes) -> bytes:
    """Descifra un bloque de 16 bytes en modo ECB."""
    ct = list(struct.unpack(">IIII", block))
    ct = [struct.unpack(">I", struct.pack("<I", x))[0] for x in ct]
    r = [ct[i] ^ subkeys[i + 4] for i in range(4)]
    for rnd in range(_ROUNDS - 1, -1, -1):
        nr = [0, 0, 0, 0]
        f0, f1 = _f(r[0], r[1], rnd, subkeys, k, s_box_keys)
        nr[2] = _rol(r[2], 1) ^ f0
        nr[3] = _ror(r[3] ^ f1, 1)
        nr[0] = r[0]
        nr[1] = r[1]
        r = nr
        if rnd > 0:
            r[0], r[2] = r[2], r[0]
            r[1], r[3] = r[3], r[1]
    r = [r[2], r[3], r[0], r[1]]
    r = [r[(i + 2) % 4] ^ subkeys[i] for i in range(4)]
    r = [struct.unpack(">I", struct.pack("<I", x))[0] for x in r]
    return struct.pack(">IIII", *r)


# ── Fast path (port exacto del C++ twofish_opt2.cpp: fullKey + fkh) ─────────

def _full_key(s_box_keys: list, k: int) -> list:
    """Precomputa QF[4][256] (S-boxes totalmente keyed).

    Convención de bytes idéntica a `_h` (myref): el byte j de la palabra se
    obtiene big-endian (MSB first), igual que `_u32_to_words(w)[j]`.
    """
    def sb(w: int, j: int) -> int:
        return (w >> (8 * (3 - j))) & 0xFF

    qf = [[0] * 256 for _ in range(4)]
    for i in range(256):
        y0 = y1 = y2 = y3 = i
        if k == 4:
            y0 = _Q1[y0] ^ sb(s_box_keys[3], 0)
            y1 = _Q0[y1] ^ sb(s_box_keys[3], 1)
            y2 = _Q0[y2] ^ sb(s_box_keys[3], 2)
            y3 = _Q1[y3] ^ sb(s_box_keys[3], 3)
            y0 = _Q1[y0] ^ sb(s_box_keys[2], 0)
            y1 = _Q1[y1] ^ sb(s_box_keys[2], 1)
            y2 = _Q0[y2] ^ sb(s_box_keys[2], 2)
            y3 = _Q0[y3] ^ sb(s_box_keys[2], 3)
            y0 = _Q1[_Q0[_Q0[y0] ^ sb(s_box_keys[1], 0)] ^ sb(s_box_keys[0], 0)]
            y1 = _Q0[_Q0[_Q1[y1] ^ sb(s_box_keys[1], 1)] ^ sb(s_box_keys[0], 1)]
            y2 = _Q1[_Q1[_Q0[y2] ^ sb(s_box_keys[1], 2)] ^ sb(s_box_keys[0], 2)]
            y3 = _Q0[_Q1[_Q1[y3] ^ sb(s_box_keys[1], 3)] ^ sb(s_box_keys[0], 3)]
        elif k == 3:
            y0 = _Q1[y0] ^ sb(s_box_keys[2], 0)
            y1 = _Q1[y1] ^ sb(s_box_keys[2], 1)
            y2 = _Q0[y2] ^ sb(s_box_keys[2], 2)
            y3 = _Q0[y3] ^ sb(s_box_keys[2], 3)
            y0 = _Q1[_Q0[_Q0[y0] ^ sb(s_box_keys[1], 0)] ^ sb(s_box_keys[0], 0)]
            y1 = _Q0[_Q0[_Q1[y1] ^ sb(s_box_keys[1], 1)] ^ sb(s_box_keys[0], 1)]
            y2 = _Q1[_Q1[_Q0[y2] ^ sb(s_box_keys[1], 2)] ^ sb(s_box_keys[0], 2)]
            y3 = _Q0[_Q1[_Q1[y3] ^ sb(s_box_keys[1], 3)] ^ sb(s_box_keys[0], 3)]
        else:  # k == 2 (clave 128 bits — caso SQLitePlus)
            y0 = _Q1[_Q0[_Q0[y0] ^ sb(s_box_keys[1], 0)] ^ sb(s_box_keys[0], 0)]
            y1 = _Q0[_Q0[_Q1[y1] ^ sb(s_box_keys[1], 1)] ^ sb(s_box_keys[0], 1)]
            y2 = _Q1[_Q1[_Q0[y2] ^ sb(s_box_keys[1], 2)] ^ sb(s_box_keys[0], 2)]
            y3 = _Q0[_Q1[_Q1[y3] ^ sb(s_box_keys[1], 3)] ^ sb(s_box_keys[0], 3)]

        qf[0][i] = ((_mult_ef[y0] << 24) | (_mult_ef[y0] << 16)
                    | (_mult_5b[y0] << 8) | y0) & 0xFFFFFFFF
        qf[1][i] = ((y1 << 24) | (_mult_5b[y1] << 16)
                    | (_mult_ef[y1] << 8) | _mult_ef[y1]) & 0xFFFFFFFF
        qf[2][i] = ((_mult_ef[y2] << 24) | (y2 << 16)
                    | (_mult_ef[y2] << 8) | _mult_5b[y2]) & 0xFFFFFFFF
        qf[3][i] = ((_mult_5b[y3] << 24) | (_mult_ef[y3] << 16)
                    | (y3 << 8) | _mult_5b[y3]) & 0xFFFFFFFF
    return qf


def _fkh(qf, x: int) -> int:
    return (qf[0][x & 0xFF] ^ qf[1][(x >> 8) & 0xFF]
            ^ qf[2][(x >> 16) & 0xFF] ^ qf[3][(x >> 24) & 0xFF])


def _encrypt_block_fast(subkeys, qf, block: bytes) -> bytes:
    """Port textual del C++ twofish_opt2.cpp encrypt(): ENC_ROUND alternado.

    Cada ENC_ROUND(R0,R1,R2,R3) computa fkh(R0),fkh(ROL(R1,8)) y escribe en
    R2,R3. La siguiente llamada pasa (R2,R3,R0,R1) — equivalencia con el
    intercambio de registros del algoritmo.
    """
    r0, r1, r2, r3 = struct.unpack("<IIII", block)
    r0 ^= subkeys[0]
    r1 ^= subkeys[1]
    r2 ^= subkeys[2]
    r3 ^= subkeys[3]
    for rnd in range(0, 16, 2):
        # ENC_ROUND(R0, R1, R2, R3, rnd)
        t0 = _fkh(qf, r0)
        t1 = _fkh(qf, _rol(r1, 8))
        r2 = _ror(r2 ^ ((t1 + t0 + subkeys[2 * rnd + 8]) & 0xFFFFFFFF), 1)
        r3 = _rol(r3, 1) ^ ((2 * t1 + t0 + subkeys[2 * rnd + 9]) & 0xFFFFFFFF)
        # ENC_ROUND(R2, R3, R0, R1, rnd+1)
        t0 = _fkh(qf, r2)
        t1 = _fkh(qf, _rol(r3, 8))
        r0 = _ror(r0 ^ ((t1 + t0 + subkeys[2 * (rnd + 1) + 8]) & 0xFFFFFFFF), 1)
        r1 = _rol(r1, 1) ^ ((2 * t1 + t0 + subkeys[2 * (rnd + 1) + 9]) & 0xFFFFFFFF)
    # output whiten
    out = struct.pack("<IIII",
                      r2 ^ subkeys[4], r3 ^ subkeys[5],
                      r0 ^ subkeys[6], r1 ^ subkeys[7])
    return out


def _decrypt_block_fast(subkeys, qf, block: bytes) -> bytes:
    """Port textual del C++ twofish_opt2.cpp decrypt(): DEC_ROUND alternado."""
    r0, r1, r2, r3 = struct.unpack("<IIII", block)
    r0 ^= subkeys[4]
    r1 ^= subkeys[5]
    r2 ^= subkeys[6]
    r3 ^= subkeys[7]
    for rnd in range(15, -1, -2):
        # DEC_ROUND(R0, R1, R2, R3, rnd)
        t0 = _fkh(qf, r0)
        t1 = _fkh(qf, _rol(r1, 8))
        r2 = _rol(r2, 1) ^ ((t0 + t1 + subkeys[2 * rnd + 8]) & 0xFFFFFFFF)
        r3 = _ror(r3 ^ ((t0 + 2 * t1 + subkeys[2 * rnd + 9]) & 0xFFFFFFFF), 1)
        # DEC_ROUND(R2, R3, R0, R1, rnd-1)
        t0 = _fkh(qf, r2)
        t1 = _fkh(qf, _rol(r3, 8))
        r0 = _rol(r0, 1) ^ ((t0 + t1 + subkeys[2 * (rnd - 1) + 8]) & 0xFFFFFFFF)
        r1 = _ror(r1 ^ ((t0 + 2 * t1 + subkeys[2 * (rnd - 1) + 9]) & 0xFFFFFFFF), 1)
    # output whiten
    out = struct.pack("<IIII",
                      r2 ^ subkeys[0], r3 ^ subkeys[1],
                      r0 ^ subkeys[2], r1 ^ subkeys[3])
    return out


class Twofish128:
    """Twofish-128 (clave de 16 bytes) con API encrypt/decrypt de bloques de 16 bytes.

    Usa el fast-path del C++ de referencia (`fullKey` → QF[4][256] + fkh con
    tablas multEF/mult5B) para descifrado rápido de grandes módulos.
    """

    def __init__(self, key: bytes):
        if len(key) > 16:
            key = key[:16]
        self._subkeys, self._k, self._s = _key_schedule(key)
        self._qf = _full_key(self._s, self._k)

    def encrypt_block(self, block: bytes) -> bytes:
        if len(block) != 16:
            raise ValueError("Twofish128 requiere bloques de 16 bytes")
        return _encrypt_block_fast(self._subkeys, self._qf, block)

    def decrypt_block(self, block: bytes) -> bytes:
        if len(block) != 16:
            raise ValueError("Twofish128 requiere bloques de 16 bytes")
        return _decrypt_block_fast(self._subkeys, self._qf, block)


def self_test() -> bool:
    """Self-test: vector oficial Twofish (key 0 / PT 0) y round-trip."""
    tf = Twofish128(b"\x00" * 16)
    ct = tf.encrypt_block(b"\x00" * 16)
    expected = bytes.fromhex("9F589F5CF6122C32B6BFEC2F2AE8C35A")
    if ct != expected:
        raise AssertionError(f"Twofish vector falló: got {ct.hex()}, esperado {expected.hex()}")

    pt = tf.decrypt_block(ct)
    if pt != b"\x00" * 16:
        raise AssertionError("Round-trip Twofish falló")

    key = b"Heb_4:12\x00\x00\x00\x00\x00\x00\x00\x00"
    tf2 = Twofish128(key)
    ct2 = tf2.encrypt_block(pt)
    if tf2.decrypt_block(ct2) != pt:
        raise AssertionError("Round-trip Twofish (clave SQLitePlus) falló")

    return True


if __name__ == "__main__":
    if self_test():
        print("Twofish128 self-test OK")
