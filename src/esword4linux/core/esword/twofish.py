def _rol(x: int, n: int) -> int:
    n &= 0x1F
    return ((x << n) & 0xFFFFFFFF) | (x >> (32 - n))


def _ror(x: int, n: int) -> int:
    n &= 0x1F
    return (x >> n) | ((x << (32 - n)) & 0xFFFFFFFF)


def _poly_mult(a: int, b: int) -> int:
    t = 0
    while a:
        if a & 1:
            t ^= b
        b <<= 1
        a >>= 1
    return t


def _gf_mod(t: int, modulus: int) -> int:
    modulus <<= 7
    for _ in range(8):
        tt = t ^ modulus
        if tt < t:
            t = tt
        modulus >>= 1
    return t


def _gf_mult(a: int, b: int, modulus: int) -> int:
    return _gf_mod(_poly_mult(a, b), modulus)


def _matrix_multiply(matrix, vector, modulus: int) -> list:
    """Multiplica una matriz GF(2^8) por un vector; devuelve resultado [MSB..LSB]."""
    result = []
    for j in range(len(matrix)):
        t = 0
        for k in range(len(vector)):
            t ^= _gf_mult(matrix[j][k], vector[k], modulus)
        result.insert(0, t)
    return result


def _words_to_u32(words: list) -> int:
    t = 0
    for w in words:
        t = (t << 8) | (w & 0xFF)
    return t


def _u32_to_words(x: int) -> list:
    return list(struct.unpack(">BBBB", struct.pack(">I", x & 0xFFFFFFFF)))


def _qpermute(x: int, q: list) -> int:
    a0, b0 = x // 16, x % 16
    a1 = a0 ^ b0
    b1 = (a0 ^ _ror4(b0, 1) ^ (8 * a0)) % 16
    a2, b2 = q[0][a1], q[1][b1]
    a3 = a2 ^ b2
    b3 = (a2 ^ _ror4(b2, 1) ^ (8 * a2)) % 16
    a4, b4 = q[2][a3], q[3][b3]
    return (16 * b4) + a4


def _ror4(x: int, n: int) -> int:
    mask = (2 ** n) - 1
    return (x >> n) | ((x & mask) << (4 - n))


